//! Process proof for the direct Canvas WASM typecheck command.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicU64, Ordering};

static NEXT_FIXTURE: AtomicU64 = AtomicU64::new(0);

#[test]
fn canvas_wasm_typecheck_uses_only_the_app_unit_graph_from_a_cold_cache() {
    let fixture = Fixture::new();
    let repository_config = fs::read_to_string(fixture.repository().join(".cargo/config.toml"))
        .expect("read repository Cargo aliases");
    assert!(
        repository_config.contains(concat!(
            "canvas-wasm-typecheck = \"clippy --locked --package app ",
            "--target wasm32-unknown-unknown -- -D warnings\"",
        )),
        "the direct alias must remain the package-scoped canonical Canvas command",
    );
    fixture.write(".cargo/config.toml", &repository_config);
    fixture.package("app", "pub fn canvas() -> u8 { 1 }\n");
    fixture.package(
        "unrelated-native",
        "compile_error!(\"unrelated native package was compiled\");\n",
    );
    fixture.package(
        "xtask",
        "compile_error!(\"the native xtask bootstrap graph was compiled\");\n",
    );
    fixture.write(
        "Cargo.toml",
        concat!(
            "[workspace]\n",
            "members = [\"app\", \"unrelated-native\", \"xtask\"]\n",
            "resolver = \"3\"\n",
        ),
    );
    fixture.write(
        "Cargo.lock",
        concat!(
            "# This file is automatically @generated by Cargo.\n",
            "version = 4\n\n",
            "[[package]]\nname = \"app\"\nversion = \"0.0.0\"\n\n",
            "[[package]]\nname = \"unrelated-native\"\nversion = \"0.0.0\"\n\n",
            "[[package]]\nname = \"xtask\"\nversion = \"0.0.0\"\n",
        ),
    );

    let output = Command::new(env!("CARGO"))
        .arg("canvas-wasm-typecheck")
        .current_dir(fixture.root())
        .env("CARGO_TARGET_DIR", fixture.root().join("cold-target"))
        .env(
            "CARGO_BUILD_BUILD_DIR",
            fixture.root().join("cold-build-dir"),
        )
        .env("RUSTC_WRAPPER", "")
        .env("RUSTC_WORKSPACE_WRAPPER", "")
        .env("CARGO_TERM_COLOR", "never")
        .output()
        .expect("launch direct Canvas WASM typecheck");
    let stderr = String::from_utf8_lossy(&output.stderr);

    assert!(output.status.success(), "{stderr}");
    assert!(stderr.contains("Checking app v0.0.0"), "{stderr}");
    assert!(!stderr.contains("unrelated-native"), "{stderr}");
    assert!(!stderr.contains("Checking xtask"), "{stderr}");
}

struct Fixture {
    repository: PathBuf,
    root: PathBuf,
}

impl Fixture {
    fn new() -> Self {
        let repository = Path::new(env!("CARGO_MANIFEST_DIR"))
            .parent()
            .expect("gate package has a repository parent");
        let root = loop {
            let ordinal = NEXT_FIXTURE.fetch_add(1, Ordering::Relaxed);
            let candidate = std::env::temp_dir().join(format!(
                "canvas-direct-fixture-{}-{ordinal}",
                std::process::id()
            ));
            match fs::create_dir(&candidate) {
                Ok(()) => break candidate,
                Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => {}
                Err(error) => panic!("create cold Canvas fixture: {error}"),
            }
        };
        Self {
            repository: repository.to_owned(),
            root,
        }
    }

    fn repository(&self) -> &Path {
        &self.repository
    }

    fn root(&self) -> &Path {
        &self.root
    }

    fn package(&self, name: &str, source: &str) {
        self.write(
            &format!("{name}/Cargo.toml"),
            &format!(
                concat!(
                    "[package]\n",
                    "name = {name:?}\n",
                    "version = \"0.0.0\"\n",
                    "edition = \"2024\"\n",
                ),
                name = name,
            ),
        );
        self.write(&format!("{name}/src/lib.rs"), source);
    }

    fn write(&self, relative: &str, contents: &str) {
        let path = self.root.join(relative);
        fs::create_dir_all(path.parent().expect("fixture file has a parent"))
            .expect("create fixture file parent");
        fs::write(path, contents).expect("write fixture file");
    }
}

impl Drop for Fixture {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.root).expect("remove cold Canvas fixture");
    }
}
