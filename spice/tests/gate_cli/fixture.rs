//! Minimal repository and process fixtures for the retained Gate CLI boundary tests.

use std::ffi::OsStr;
use std::fs;
use std::os::unix::fs::PermissionsExt as _;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicU64, Ordering};

pub(super) struct GateRepository {
    scratch: Scratch,
}

impl GateRepository {
    pub(super) fn new() -> Self {
        let scratch = Scratch::new("repository");
        git(scratch.path(), &["init", "-q"]);
        git(
            scratch.path(),
            &["config", "user.email", "gate@example.invalid"],
        );
        git(scratch.path(), &["config", "user.name", "Gate Fixture"]);
        fs::create_dir(scratch.path().join("src")).expect("create source directory");
        fs::write(
            scratch.path().join("spice-rust.toml"),
            format!(
                "{}[policy]\ntest_engines = [\"cargo-workspace\"]\n\n[gate.walk]\nskip = []\n",
                gate::NARROWEST_FILE_CLASSES,
            ),
        )
        .expect("write tracked policy");
        fs::write(
            scratch.path().join("baseline.toml"),
            "version = 1\n\n[[floor]]\nname = \"rust.mutation-survivors\"\nvalue = 0\n",
        )
        .expect("write tracked baseline");
        fs::write(
            scratch.path().join("Cargo.toml"),
            "[package]\nname = \"gate-fixture\"\nversion = \"0.0.0\"\nedition = \"2024\"\n",
        )
        .expect("write fixture Cargo manifest");
        fs::write(
            scratch.path().join("Cargo.lock"),
            concat!(
                "# This file is automatically @generated by Cargo.\n",
                "# It is not intended for manual editing.\n",
                "version = 4\n\n",
                "[[package]]\n",
                "name = \"gate-fixture\"\n",
                "version = \"0.0.0\"\n",
            ),
        )
        .expect("write fixture Cargo lockfile");
        fs::write(scratch.path().join("src/lib.rs"), "pub fn fixture() {}\n")
            .expect("write fixture source");
        fs::write(scratch.path().join(".gitignore"), "/target/\n")
            .expect("ignore fixture build cache");
        git(scratch.path(), &["add", "."]);
        git(scratch.path(), &["commit", "-qm", "fixture"]);
        Self { scratch }
    }

    pub(super) fn path(&self) -> &Path {
        self.scratch.path()
    }

    pub(super) fn add(&self, path: &str) {
        git(self.path(), &["add", path]);
    }

    pub(super) fn write_selected_test(&self, marker: &Path) {
        let marker = format!("{:?}", marker.to_string_lossy());
        fs::write(
            self.path().join("src/lib.rs"),
            format!(
                concat!(
                    "pub fn fixture() {{}}\n\n",
                    "#[test]\n",
                    "fn canonical_selected_target() {{\n",
                    "    use std::io::Write as _;\n",
                    "    let mut marker = std::fs::OpenOptions::new()\n",
                    "        .create(true)\n",
                    "        .append(true)\n",
                    "        .open({marker})\n",
                    "        .expect(\"open marker\");\n",
                    "    writeln!(marker, \"canonical selected target executed\")\n",
                    "        .expect(\"append marker\");\n",
                    "}}\n",
                ),
                marker = marker,
            ),
        )
        .expect("write selected target");
    }
}

pub(super) fn git(root: &Path, arguments: &[&str]) {
    let output = fixture_command("/usr/bin/git")
        .args(arguments)
        .current_dir(root)
        .output()
        .expect("fixture Git launches");
    assert!(
        output.status.success(),
        "git {arguments:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

#[expect(
    clippy::disallowed_methods,
    reason = "the process-fixture rim inherits PATH and pins its exact Cargo ahead of it"
)]
pub(super) fn fixture_command(program: impl AsRef<OsStr>) -> Command {
    let cargo_bin = Path::new(env!("CARGO"))
        .parent()
        .expect("the Cargo executable has a parent directory");
    let ambient_path = std::env::var_os("PATH").unwrap_or_default();
    let path = std::env::join_paths(
        std::iter::once(cargo_bin.to_path_buf()).chain(std::env::split_paths(&ambient_path)),
    )
    .expect("the fixture Cargo directory joins the ambient PATH");
    let mut command = Command::new(program);
    command
        .env("PATH", path)
        .env_remove("GIT_INDEX_FILE") // env-policy: allow
        .env_remove(spice::install::INSTALLED_PRE_COMMIT_ENVIRONMENT)
        .env_remove(wire::SpiceVariable::PreCommitPaths.as_str())
        .env_remove(wire::SpiceVariable::PreCommitSource.as_str());
    command
}

pub(super) struct Scratch(PathBuf);

impl Scratch {
    pub(super) fn new(label: &str) -> Self {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let path = std::env::temp_dir().join(format!(
            "spice-gate-cli-{label}-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir(&path).expect("create unique gate scratch");
        Self(path)
    }

    pub(super) fn path(&self) -> &Path {
        &self.0
    }
}

impl Drop for Scratch {
    fn drop(&mut self) {
        remove_scratch(&self.0)
            .unwrap_or_else(|error| panic!("remove {}: {error}", self.0.display()));
    }
}

fn remove_scratch(path: &Path) -> std::io::Result<()> {
    match fs::remove_dir_all(path) {
        Ok(()) => return Ok(()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(()),
        Err(_) => make_tree_writable(path),
    }
    match fs::remove_dir_all(path) {
        Ok(()) => Ok(()),
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => Ok(()),
        Err(error) => Err(error),
    }
}

fn make_tree_writable(path: &Path) {
    let Ok(metadata) = fs::metadata(path) else {
        return;
    };
    let mut permissions = metadata.permissions();
    permissions.set_mode(permissions.mode() | 0o700);
    let _ = fs::set_permissions(path, permissions);
    if let Ok(entries) = fs::read_dir(path) {
        for entry in entries.flatten() {
            make_tree_writable(&entry.path());
        }
    }
}
