//! The Rust-only Git shadow path and bytes, pinned.
//!
//! Python owns `<git-dir>/agent.gitconfig`; this runtime owns
//! `<git-dir>/spice-rs-agent.gitconfig`. The positive and negative assertions
//! hold both names independently while the byte assertions preserve the native
//! shadow's existing Git semantics. Everything runs against a linked worktree.
//! In an ordinary checkout `--absolute-git-dir` and `--git-common-dir` name the
//! same directory, so a test placed there passes whichever one the code asks
//! for, and the divergence this file exists to catch would be invisible.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;
use std::sync::atomic::{AtomicU64, Ordering};

use sill::Environment;
use spice::repository::Repository;

/// Filename this runtime owns, restated independently of production code.
const RUST_GITCONFIG_NAME: &str = "spice-rs-agent.gitconfig";

/// Filename the Python predecessor owns and this runtime must never publish.
const PYTHON_GITCONFIG_NAME: &str = "agent.gitconfig";

/// First line of the Rust-only shadow.
const SHADOW_HEADER: &str = "# Generated by spice-rs for the per-process agent git shadow.";

/// The shadow lands in the per-worktree Git directory, not the common one.
///
/// A linked worktree separates the two: `--absolute-git-dir` reports
/// `<common>/worktrees/<name>` while `--git-common-dir` reports `<common>`, and
/// the worktree's own `.git` is a file rather than a directory. The positive
/// assertion names the first, and the negative one denies the second, so
/// resolving the anchor the other way reds this test rather than relocating a
/// file the predecessor will then write again beside it.
#[test]
fn the_git_shadow_is_written_to_the_per_worktree_git_directory() {
    let fixture = Fixture::new("anchor");
    let repository = Repository::discover(&fixture.linked).expect("linked worktree resolves");

    let environment = spice::git_shadow::environment(&repository, fixture.base())
        .expect("the Git shadow composes over a linked worktree");

    assert_ne!(
        fixture.common,
        fixture.per_worktree_git_dir(),
        "the fixture is not a linked worktree, so it cannot tell the two anchors \
         apart and the assertions below would hold either way"
    );
    let published = fixture.per_worktree_git_dir().join(RUST_GITCONFIG_NAME);
    assert_eq!(
        Path::new(shadow_path(&environment)),
        published,
        "the shadow was published somewhere other than the per-worktree Git directory"
    );
    assert!(
        fs::read_to_string(&published)
            .expect("the environment names a shadow that was written")
            .contains(&format!("[branch \"{}\"]", fixture.branch)),
        "a file exists at {} but it is not the shadow for this worktree's branch",
        published.display()
    );
    assert!(
        !fixture.common.join(RUST_GITCONFIG_NAME).exists(),
        "the shadow was written to the common Git directory, where one worktree's \
         branch would overwrite every other worktree's"
    );
    assert!(
        !fixture
            .per_worktree_git_dir()
            .join(PYTHON_GITCONFIG_NAME)
            .exists(),
        "publishing the Rust shadow touched Python's shadow path"
    );
}

/// Publishing twice leaves the byte-identical file the second run found.
///
/// Rust compares before writing. A port that stopped comparing would still
/// pass the anchor assertion above while pointlessly rewriting its own file on
/// every run, so the modification time catches a write that changed nothing.
#[test]
fn a_second_publication_rewrites_nothing() {
    let fixture = Fixture::new("idempotent");
    let repository = Repository::discover(&fixture.linked).expect("linked worktree resolves");

    spice::git_shadow::environment(&repository, fixture.base()).expect("the first shadow composes");
    let published = fixture.per_worktree_git_dir().join(RUST_GITCONFIG_NAME);
    let first = fs::metadata(&published).expect("the first run published the shadow");
    let written = fs::read(&published).expect("the published shadow reads back");

    spice::git_shadow::environment(&repository, fixture.base())
        .expect("the second shadow composes");

    let second = fs::metadata(&published).expect("the shadow survives a second run");
    assert_eq!(
        fs::read(&published).expect("the shadow reads back unchanged"),
        written,
        "the second run changed the Rust shadow bytes"
    );
    assert_eq!(
        first
            .modified()
            .expect("a published shadow carries a modification time"),
        second
            .modified()
            .expect("a surviving shadow carries a modification time"),
        "the second run republished identical bytes instead of leaving the file alone"
    );
}

/// The published shadow opens with its Rust-only header.
///
/// The comparison keeps the newline rather than reading a first line back:
/// `lines()` strips a trailing carriage return, so a CRLF divergence would read
/// here as agreement even though the bytes differ.
#[test]
fn the_published_shadow_opens_with_the_rust_only_header() {
    let fixture = Fixture::new("header");
    let repository = Repository::discover(&fixture.linked).expect("linked worktree resolves");

    spice::git_shadow::environment(&repository, fixture.base())
        .expect("the Git shadow composes over a linked worktree");

    let published = fs::read_to_string(fixture.per_worktree_git_dir().join(RUST_GITCONFIG_NAME))
        .expect("the environment names a shadow that was written");
    assert!(
        published.starts_with(&format!("{SHADOW_HEADER}\n")),
        "the shadow opens {:?}, not the Rust-only header",
        published.lines().next().unwrap_or_default(),
    );
}

/// A simple branch pins the whole Rust shadow file.
///
/// The expected bytes are deliberately restated here rather than assembled by
/// the production module. That makes section reordering, spaces in place of
/// tabs, or a missing final newline independently observable.
#[test]
fn a_simple_branch_publishes_the_exact_rust_shadow_bytes() {
    let fixture = Fixture::new("bytes");
    let repository = Repository::discover(&fixture.linked).expect("linked worktree resolves");

    spice::git_shadow::environment(&repository, fixture.base())
        .expect("the Git shadow composes over a linked worktree");

    let expected = format!(
        concat!(
            "{}\n",
            "[include]\n",
            "\tpath = {}\n",
            "[branch \"lane-bytes\"]\n",
            "\tmerge = refs/heads/lane-bytes\n",
        ),
        SHADOW_HEADER,
        git_system_config_path(),
    );
    assert_eq!(
        fs::read(fixture.per_worktree_git_dir().join(RUST_GITCONFIG_NAME))
            .expect("the published shadow reads back"),
        expected.as_bytes(),
        "the Rust shadow bytes drifted",
    );
}

/// A Git-valid double quote is escaped in the subsection and nowhere else.
///
/// Git refuses backslashes in refnames, so the production comment records that
/// half of the escape pair as defensive. A quote is
/// valid and reaches the writer through a real branch, making its order here a
/// load-bearing byte contract.
#[test]
fn a_quoted_branch_publishes_the_exact_rust_subsection() {
    let fixture = Fixture::with_branch("quoted", "lane-quo\"te");
    let repository = Repository::discover(&fixture.linked).expect("linked worktree resolves");

    spice::git_shadow::environment(&repository, fixture.base())
        .expect("the Git shadow composes over a linked worktree");

    let published = fs::read_to_string(fixture.per_worktree_git_dir().join(RUST_GITCONFIG_NAME))
        .expect("the published shadow reads back");
    assert!(
        published.contains("[branch \"lane-quo\\\"te\"]\n"),
        "the reachable subsection quote no longer matches the Rust shadow: {published:?}",
    );
}

/// The `GIT_CONFIG_SYSTEM` value the shadow published.
fn shadow_path(environment: &Environment) -> &std::ffi::OsStr {
    environment
        .entries()
        .iter()
        .find(|(key, _)| key == "GIT_CONFIG_SYSTEM")
        .map(|(_, value)| value.as_os_str())
        .expect("the Git shadow names its system config")
}

/// One committed repository and one linked worktree checked out beside it.
struct Fixture {
    common: PathBuf,
    linked: PathBuf,
    branch: String,
}

impl Fixture {
    fn new(label: &str) -> Self {
        Self::with_branch(label, &format!("lane-{label}"))
    }

    fn with_branch(label: &str, branch: &str) -> Self {
        static NEXT: AtomicU64 = AtomicU64::new(0);
        let root = std::env::temp_dir().join(format!(
            "spice-git-shadow-{label}-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir(&root).expect("create Git shadow fixture root");
        git(&root, &["init", "-q"]);
        git(&root, &["config", "user.email", "shadow@example.invalid"]);
        git(&root, &["config", "user.name", "Git Shadow Fixture"]);
        fs::write(root.join("README.md"), "fixture\n").expect("seed a tracked file");
        git(&root, &["add", "README.md"]);
        git(&root, &["commit", "-qm", "fixture commit"]);
        // Canonical from here on: the runtime canonicalizes while discovering,
        // and on macOS the temporary directory is reached through a symlink, so
        // an uncanonicalized root would never equal the paths it reports.
        let root = fs::canonicalize(&root).expect("canonicalize fixture root");

        let branch = branch.to_owned();
        let linked = root.join("lane");
        git(
            &root,
            &[
                "worktree",
                "add",
                "-q",
                "-b",
                &branch,
                linked.to_str().expect("fixture path is text"),
            ],
        );
        Self {
            common: root.join(".git"),
            linked,
            branch,
        }
    }

    /// The directory `rev-parse --absolute-git-dir` reports for the worktree.
    fn per_worktree_git_dir(&self) -> PathBuf {
        self.common.join("worktrees").join(
            self.linked
                .file_name()
                .expect("the linked worktree is named"),
        )
    }

    /// An environment carrying only what launching Git needs.
    ///
    /// Nothing Git-related is inherited: the shadow filters `GIT_CONFIG_*` out of
    /// the environment it probes with, and a caller's real `GIT_CONFIG_SYSTEM`
    /// leaking in would be read back as this test's own answer.
    fn base(&self) -> Environment {
        Environment::new([("PATH", "/usr/bin:/bin")]).expect("fixture environment admits")
    }
}

/// The system config path resolved by the independently spelled Git probe.
fn git_system_config_path() -> String {
    let output = Command::new("/usr/bin/git")
        .args(["config", "--system", "--edit"])
        .env_clear()
        .env("PATH", "/usr/bin:/bin")
        .env("GIT_EDITOR", "echo")
        .output()
        .expect("the independent system-config probe launches");
    assert!(
        output.status.success(),
        "git config --system --edit failed: {}",
        String::from_utf8_lossy(&output.stderr),
    );
    String::from_utf8(output.stdout)
        .expect("the system-config path is text")
        .trim()
        .to_owned()
}

fn git(root: &Path, arguments: &[&str]) {
    let output = Command::new("/usr/bin/git")
        .args(arguments)
        .current_dir(root)
        .output()
        .expect("Git shadow fixture Git launches");
    assert!(
        output.status.success(),
        "git {arguments:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}
