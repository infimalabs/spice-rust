use std::collections::BTreeMap;
use std::ffi::OsString;
use std::fs;
use std::path::{Path, PathBuf};

use sill::Environment;

use super::{GitAnswer, Pairing, compose, declare};

const SYSTEM_CONFIG: &str = "/fixture/system.gitconfig";

/// One scratch Git directory, removed again when the test that made it ends.
struct Scratch(PathBuf);

impl Drop for Scratch {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}

fn scratch(label: &str) -> Scratch {
    let root = std::env::temp_dir().join(format!(
        "spice-git-shadow-{label}-{}-{}",
        std::process::id(),
        uuid::Uuid::new_v4()
    ));
    fs::create_dir(&root).expect("scratch Git directory creates");
    Scratch(root)
}

/// Git as one worktree on `branch` with its own Git directory answers it.
///
/// Every other query reports nothing, as Git does for an unset key, and every
/// query records the environment it was asked under.
fn worktree<'a>(
    branch: &'a str,
    git_dir: &'a Path,
    merge: Option<&'a str>,
    asked: &'a mut Vec<BTreeMap<OsString, OsString>>,
) -> impl FnMut(&[&str], &BTreeMap<OsString, OsString>) -> GitAnswer + 'a {
    move |arguments, environment| {
        asked.push(environment.clone());
        let merge_key = format!("branch.{branch}.merge");
        Ok(match arguments {
            ["symbolic-ref", "--quiet", "--short", "HEAD"] => Some(branch.to_owned()),
            ["rev-parse", "--absolute-git-dir"] => Some(git_dir.display().to_string()),
            ["config", "--system", "--edit"] => Some(SYSTEM_CONFIG.to_owned()),
            ["config", "--get", key] if *key == merge_key => merge.map(str::to_owned),
            _ => None,
        })
    }
}

fn value<'a>(environment: &'a Environment, key: &str) -> Option<&'a str> {
    environment
        .entries()
        .iter()
        .find(|(name, _)| name == key)
        .and_then(|(_, value)| value.to_str())
}

/// The command-scope pairs the composed environment carries, in index order.
fn command_scope(environment: &Environment) -> Vec<(String, String)> {
    let count = value(environment, "GIT_CONFIG_COUNT").map_or(0, |count| {
        count.parse::<usize>().expect("GIT_CONFIG_COUNT is a count")
    });
    (0..count)
        .map(|index| {
            let pair = |prefix: &str| {
                value(environment, &format!("{prefix}{index}"))
                    .expect("every counted pair is present")
                    .to_owned()
            };
            (pair("GIT_CONFIG_KEY_"), pair("GIT_CONFIG_VALUE_"))
        })
        .collect()
}

/// The shadow lands in the Git directory `--absolute-git-dir` names, which is
/// the per-worktree one in a linked worktree, and becomes the system scope.
#[test]
fn the_shadow_is_published_in_the_worktree_git_directory_as_system_scope() {
    let scratch = scratch("publish");
    let mut asked = Vec::new();

    let composed = compose(
        Environment::new([("PATH", "/usr/bin")]).expect("base"),
        worktree("lane-bytes", &scratch.0, None, &mut asked),
    )
    .expect("the shadow composes");

    let published = scratch.0.join("agent.gitconfig");
    assert_eq!(
        value(&composed, "GIT_CONFIG_SYSTEM"),
        Some(published.to_str().expect("UTF-8 scratch path"))
    );
    assert_eq!(
        fs::read_to_string(&published).expect("the shadow was written"),
        concat!(
            "# Generated by spice for the per-process agent git shadow.\n",
            "[include]\n",
            "\tpath = /fixture/system.gitconfig\n",
            "[branch \"lane-bytes\"]\n",
            "\tmerge = refs/heads/lane-bytes\n",
        )
    );
    assert_eq!(value(&composed, "PATH"), Some("/usr/bin"));
    assert_eq!(
        command_scope(&composed),
        vec![("branch.lane-bytes.remote".to_owned(), ".".to_owned())]
    );
}

/// The true integration branch rides the final command scope, and Git is never
/// asked under a shadow the caller already inherited.
#[test]
fn the_true_merge_rides_the_command_scope_over_an_inherited_shadow() {
    let scratch = scratch("merge");
    let mut asked = Vec::new();
    let base = Environment::new([
        ("PATH", "/usr/bin"),
        ("GIT_CONFIG_SYSTEM", "/inherited/shadow"),
        ("GIT_CONFIG_COUNT", "1"),
        ("GIT_CONFIG_KEY_0", "branch.lane.merge"),
        ("GIT_CONFIG_VALUE_0", "refs/heads/stale"),
    ])
    .expect("base");

    let composed = compose(
        base,
        worktree("lane", &scratch.0, Some("refs/heads/main"), &mut asked),
    )
    .expect("the shadow composes");

    assert_eq!(
        command_scope(&composed),
        vec![
            ("branch.lane.merge".to_owned(), "refs/heads/main".to_owned()),
            ("branch.lane.remote".to_owned(), ".".to_owned()),
        ]
    );
    assert!(!asked.is_empty());
    for environment in &asked {
        assert!(
            environment
                .keys()
                .all(|key| !key.to_string_lossy().starts_with("GIT_CONFIG")),
            "Git was asked under an inherited shadow: {environment:?}"
        );
    }
}

/// A detached head leaves the caller's environment exactly as it was.
#[test]
fn a_detached_head_composes_no_shadow() {
    let scratch = scratch("detached");
    let base = Environment::new([("PATH", "/usr/bin")]).expect("base");

    let composed = compose(base.clone(), |arguments, _| {
        Ok(match arguments {
            ["rev-parse", "--absolute-git-dir"] => Some(scratch.0.display().to_string()),
            _ => None,
        })
    })
    .expect("a detached head is not an error");

    assert_eq!(composed, base);
    assert!(!scratch.0.join("agent.gitconfig").exists());
}

/// A Git-valid double quote is escaped in the subsection and nowhere else.
#[test]
fn a_quoted_branch_is_escaped_only_in_its_subsection() {
    let scratch = scratch("quoted");
    let mut asked = Vec::new();

    compose(
        Environment::new([("PATH", "/usr/bin")]).expect("base"),
        worktree("lane-quo\"te", &scratch.0, None, &mut asked),
    )
    .expect("the shadow composes");

    let published =
        fs::read_to_string(scratch.0.join("agent.gitconfig")).expect("the shadow was written");
    assert!(published.contains("[branch \"lane-quo\\\"te\"]\n"));
    assert!(published.contains("\tmerge = refs/heads/lane-quo\"te\n"));
}

/// Publishing twice leaves the byte-identical file the first run wrote.
#[test]
fn a_second_publication_rewrites_nothing() {
    let scratch = scratch("idempotent");
    let published = scratch.0.join("agent.gitconfig");
    let mut asked = Vec::new();
    let base = Environment::new([("PATH", "/usr/bin")]).expect("base");

    compose(base.clone(), worktree("lane", &scratch.0, None, &mut asked))
        .expect("the first shadow composes");
    let first = fs::metadata(&published).expect("the first run published");
    compose(base, worktree("lane", &scratch.0, None, &mut asked))
        .expect("the second shadow composes");
    let second = fs::metadata(&published).expect("the shadow survives");

    assert_eq!(
        first.modified().expect("modification time"),
        second.modified().expect("modification time"),
        "the second run republished identical bytes"
    );
}

/// The pairing `lane` reads when its configuration holds `remote` and `merge`.
fn declared(remote: Option<&str>, merge: Option<&str>) -> Result<Option<Pairing>, super::Error> {
    declare("lane", |arguments| {
        Ok(match arguments {
            ["config", "--get", "branch.lane.remote"] => remote.map(str::to_owned),
            ["config", "--get", "branch.lane.merge"] => merge.map(str::to_owned),
            other => panic!("unexpected Git query {other:?}"),
        })
    })
}

#[test]
fn a_dot_pairing_protects_the_local_branch_it_integrates_into() {
    let pairing = declared(Some("."), Some("refs/heads/main"))
        .expect("a whole pairing reads")
        .expect("the pairing is declared");

    assert!(pairing.is_local());
    assert_eq!(pairing.branch, "main");
    assert_eq!(pairing.reference(), "refs/heads/main");
}

#[test]
fn a_remote_pairing_names_its_remote_tracking_branch() {
    let pairing = declared(Some("upstream"), Some("refs/heads/trunk"))
        .expect("a whole pairing reads")
        .expect("the pairing is declared");

    assert!(!pairing.is_local());
    assert_eq!(pairing.reference(), "refs/remotes/upstream/trunk");
}

#[test]
fn only_a_branch_declaring_neither_half_is_untracked() {
    assert_eq!(declared(None, None).expect("nothing declared reads"), None);
    for (remote, merge) in [
        (Some("origin"), None),
        (None, Some("refs/heads/main")),
        (Some("origin"), Some("main")),
    ] {
        assert!(
            declared(remote, merge).is_err(),
            "remote {remote:?} with merge {merge:?} passed for a pairing"
        );
    }
}
